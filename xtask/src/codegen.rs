//! Code generation: `koha-lock.json` and `data/koha-<series>/*.json` become Rust in
//! `crates/atrium-data/src/generated/`.
//!
//! `codegen` writes the files; `codegen --check` fails when a committed file differs from
//! what would be generated, so CI catches hand edits and forgotten regenerations.

use std::fmt::Write as _;
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use serde_json::Value;

/// Where generated Rust goes, relative to the workspace root.
const OUT_DIR: &str = "crates/atrium-data/src/generated";

/// Write mode or check mode.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Mode {
    /// Overwrite the generated files.
    Write,
    /// Compare only; fail on any difference.
    Check,
}

/// Path of an extracted data file, relative to the repository root.
fn data_path(series: &str, name: &str) -> String {
    format!("data/koha-{series}/{name}")
}

/// One generated file: path relative to [`OUT_DIR`] and its unformatted contents.
struct Generated {
    name: String,
    source: String,
}

/// Generates every file and writes or checks it according to `mode`.
pub(crate) fn run(root: &Path, mode: Mode) -> Result<(), String> {
    let lock = read_json(&root.join("koha-lock.json"))?;
    let series = str_field(&lock, "series")?;
    let data = |name: &str| read_json(&root.join(data_path(series, name)));
    let rule_kinds = data("circulation_rule_kinds.json")?;
    let framework = data("marc21_framework.json")?;
    let iso5426 = data("iso5426.json")?;
    let search_fields = data("search_fields.json")?;

    let mut files = vec![
        Generated {
            name: "mod.rs".to_owned(),
            source: module_index(),
        },
        Generated {
            name: "koha_version.rs".to_owned(),
            source: koha_version(&lock)?,
        },
        Generated {
            name: "circulation_rule_kinds.rs".to_owned(),
            source: circulation_rule_kinds(&rule_kinds)?,
        },
        Generated {
            name: "iso5426.rs".to_owned(),
            source: crate::charsets::iso5426(
                &iso5426,
                &data_path(series, "iso5426.json"),
                &header(&data_path(series, "iso5426.json")),
            )?,
        },
        Generated {
            name: "search_fields.rs".to_owned(),
            source: crate::search_fields::generate(
                &search_fields,
                &data_path(series, "search_fields.json"),
                &header(&data_path(series, "search_fields.json")),
            )?,
        },
    ];
    files.extend(
        crate::marc_framework::files(
            &framework,
            &data_path(series, "marc21_framework.json"),
            &header,
        )?
        .into_iter()
        .map(|file| Generated {
            name: file.name,
            source: file.source,
        }),
    );

    let out_dir = root.join(OUT_DIR);
    let mut stale = Vec::new();
    for file in &files {
        let path = out_dir.join(&file.name);
        let text = rustfmt(&file.source)?;
        match mode {
            Mode::Write => {
                std::fs::create_dir_all(&out_dir)
                    .map_err(|e| format!("cannot create {}: {e}", out_dir.display()))?;
                std::fs::write(&path, text)
                    .map_err(|e| format!("cannot write {}: {e}", path.display()))?;
            }
            Mode::Check => {
                let current = std::fs::read_to_string(&path).unwrap_or_default();
                if current != text {
                    stale.push(display(root, &path));
                }
            }
        }
    }
    if stale.is_empty() {
        println!(
            "codegen: {} files {} in {OUT_DIR}",
            files.len(),
            if mode == Mode::Write {
                "written"
            } else {
                "up to date"
            }
        );
        Ok(())
    } else {
        Err(format!(
            "generated files are stale (run `cargo xtask codegen`):\n  {}",
            stale.join("\n  ")
        ))
    }
}

/// Header placed on every generated file.
fn header(from: &str) -> String {
    format!(
        "// SPDX-License-Identifier: GPL-3.0-or-later\n\
         // @generated by `cargo xtask codegen` from {from}. Do not edit by hand.\n\n"
    )
}

fn module_index() -> String {
    let mut out = header("xtask/src/codegen.rs");
    out.push_str(
        "//! Tables generated from the pinned Koha reference.\n\n\
         #[expect(clippy::too_many_lines, reason = \"one match arm per Koha rule kind\")]\n\
         pub(crate) mod circulation_rule_kinds;\n\
         pub(crate) mod iso5426;\n\
         pub(crate) mod koha_version;\n\
         pub(crate) mod marc21_framework_0xx;\n\
         pub(crate) mod marc21_framework_1xx;\n\
         pub(crate) mod marc21_framework_2xx;\n\
         pub(crate) mod marc21_framework_3xx;\n\
         pub(crate) mod marc21_framework_4xx;\n\
         pub(crate) mod marc21_framework_5xx;\n\
         pub(crate) mod marc21_framework_6xx;\n\
         pub(crate) mod marc21_framework_7xx;\n\
         pub(crate) mod marc21_framework_8xx;\n\
         pub(crate) mod marc21_framework_9xx;\n\
         pub(crate) mod search_fields;\n",
    );
    out
}

fn koha_version(lock: &Value) -> Result<String, String> {
    let mut out = header("koha-lock.json");
    write!(
        out,
        "//! The pinned Koha reference release.\n\n\
         use crate::KohaReference;\n\n\
         /// The Koha release Atrium is checked against (`koha-lock.json`).\n\
         pub const KOHA_REFERENCE: KohaReference = KohaReference {{\n\
             version: {:?},\n\
             tag: {:?},\n\
             commit: {:?},\n\
         }};\n",
        str_field(lock, "version")?,
        str_field(lock, "tag")?,
        str_field(lock, "commit")?,
    )
    .map_err(fmt_error)?;
    Ok(out)
}

/// A circulation rule kind as read from the extractor output.
struct RuleKindRow {
    name: String,
    variant: String,
    scope: Vec<&'static str>,
    can_be_blank: bool,
    is_monetary: bool,
}

fn circulation_rule_kinds(json: &Value) -> Result<String, String> {
    let rows = rule_kind_rows(json)?;
    let source_file = json
        .pointer("/source/file")
        .and_then(Value::as_str)
        .ok_or("circulation_rule_kinds.json has no source.file")?;
    let count = rows.len();

    let mut out = header("data/koha-<series>/circulation_rule_kinds.json");
    write!(
        out,
        "//! Kinds of circulation rule.\n//!\n\
         //! Koha: `Koha::CirculationRules::$RULE_KINDS` in `{source_file}`.\n\n\
         use crate::{{RuleKindInfo, RuleScope}};\n\n\
         /// A kind of circulation rule, one per entry of Koha's `$RULE_KINDS`.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]\n\
         pub enum RuleKind {{\n"
    )
    .map_err(fmt_error)?;
    for row in &rows {
        writeln!(
            out,
            "    /// Koha rule `{}`.\n    {},",
            row.name, row.variant
        )
        .map_err(fmt_error)?;
    }
    write!(
        out,
        "}}\n\nimpl RuleKind {{\n\
         /// Every rule kind, sorted by Koha name.\n\
         pub const ALL: [Self; {count}] = [\n"
    )
    .map_err(fmt_error)?;
    for row in &rows {
        writeln!(out, "Self::{},", row.variant).map_err(fmt_error)?;
    }
    out.push_str(
        "];\n\n\
         /// Static facts about this rule kind.\n\
         #[must_use]\n\
         pub const fn info(self) -> &'static RuleKindInfo {\n\
         match self {\n",
    );
    for row in &rows {
        let scope = row
            .scope
            .iter()
            .map(|s| format!("RuleScope::{s}"))
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(
            out,
            "Self::{} => &RuleKindInfo {{ koha_name: {:?}, scope: &[{scope}], \
             can_be_blank: {}, is_monetary: {} }},",
            row.variant, row.name, row.can_be_blank, row.is_monetary
        )
        .map_err(fmt_error)?;
    }
    out.push_str(
        "}\n}\n\n\
         /// Looks a rule kind up by the name Koha stores in `circulation_rules.rule_name`.\n\
         #[must_use]\n\
         pub fn from_koha_name(name: &str) -> Option<Self> {\n\
         match name {\n",
    );
    for row in &rows {
        writeln!(out, "{:?} => Some(Self::{}),", row.name, row.variant).map_err(fmt_error)?;
    }
    out.push_str("_ => None,\n}\n}\n}\n");
    Ok(out)
}

fn rule_kind_rows(json: &Value) -> Result<Vec<RuleKindRow>, String> {
    let kinds = json
        .get("rule_kinds")
        .and_then(Value::as_array)
        .ok_or("circulation_rule_kinds.json has no rule_kinds array")?;
    let mut rows = Vec::with_capacity(kinds.len());
    for kind in kinds {
        let name = str_field(kind, "name")?.to_owned();
        let scope = kind
            .get("scope")
            .and_then(Value::as_array)
            .ok_or(format!("rule `{name}` has no scope array"))?
            .iter()
            .map(|s| scope_variant(s.as_str().unwrap_or_default(), &name))
            .collect::<Result<Vec<_>, _>>()?;
        rows.push(RuleKindRow {
            variant: camel_case(&name),
            scope,
            can_be_blank: bool_field(kind, "can_be_blank", &name)?,
            is_monetary: bool_field(kind, "is_monetary", &name)?,
            name,
        });
    }
    let mut variants: Vec<&str> = rows.iter().map(|r| r.variant.as_str()).collect();
    variants.sort_unstable();
    if variants.windows(2).any(|pair| pair.first() == pair.last()) {
        return Err("two rule kinds map to the same Rust variant name".to_owned());
    }
    Ok(rows)
}

/// Maps Koha's scope column names to [`atrium_data::RuleScope`] variants.
fn scope_variant(koha: &str, rule: &str) -> Result<&'static str, String> {
    match koha {
        "branchcode" => Ok("Branch"),
        "categorycode" => Ok("PatronCategory"),
        "itemtype" => Ok("ItemType"),
        other => Err(format!("rule `{rule}` has unknown scope `{other}`")),
    }
}

/// `max_holds` → `MaxHolds`.
pub(crate) fn camel_case(snake: &str) -> String {
    snake
        .split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            chars.next().map_or_else(String::new, |first| {
                first.to_ascii_uppercase().to_string() + chars.as_str()
            })
        })
        .collect()
}

/// Formats generated source with the workspace's rustfmt settings.
fn rustfmt(source: &str) -> Result<String, String> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| format!("cannot run rustfmt: {e}"))?;
    child
        .stdin
        .take()
        .ok_or("rustfmt has no stdin")?
        .write_all(source.as_bytes())
        .map_err(|e| format!("cannot write to rustfmt: {e}"))?;
    let output = child
        .wait_with_output()
        .map_err(|e| format!("rustfmt failed: {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "rustfmt rejected generated code:\n{}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    String::from_utf8(output.stdout).map_err(|e| format!("rustfmt output is not UTF-8: {e}"))
}

fn read_json(path: &PathBuf) -> Result<Value, String> {
    let text = std::fs::read_to_string(path)
        .map_err(|e| format!("cannot read {}: {e}", path.display()))?;
    serde_json::from_str(&text).map_err(|e| format!("{} is not JSON: {e}", path.display()))
}

fn str_field<'a>(json: &'a Value, key: &str) -> Result<&'a str, String> {
    json.get(key)
        .and_then(Value::as_str)
        .ok_or(format!("missing string field `{key}`"))
}

fn bool_field(json: &Value, key: &str, rule: &str) -> Result<bool, String> {
    json.get(key)
        .and_then(Value::as_bool)
        .ok_or(format!("rule `{rule}` has no boolean `{key}`"))
}

/// Writing to a `String` cannot fail, but the error is still propagated, not dropped.
fn fmt_error(e: std::fmt::Error) -> String {
    format!("formatting generated code failed: {e}")
}

fn display(root: &Path, path: &Path) -> String {
    path.strip_prefix(root)
        .unwrap_or(path)
        .display()
        .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn camel_case_joins_snake_case_words() {
        assert_eq!(camel_case("max_holds"), "MaxHolds");
        assert_eq!(camel_case("lostreturn"), "Lostreturn");
        assert_eq!(camel_case("patron_maxissueqty"), "PatronMaxissueqty");
    }

    #[test]
    fn unknown_scope_is_an_error() {
        let json: Value = serde_json::from_str(
            r#"{ "source": { "file": "x" }, "rule_kinds": [
                { "name": "r", "scope": ["shelf"], "can_be_blank": true, "is_monetary": false }
            ] }"#,
        )
        .unwrap();
        let err = circulation_rule_kinds(&json).unwrap_err();
        assert!(err.contains("unknown scope `shelf`"), "{err}");
    }

    #[test]
    fn colliding_variant_names_are_an_error() {
        let json: Value = serde_json::from_str(
            r#"{ "source": { "file": "x" }, "rule_kinds": [
                { "name": "a_b", "scope": [], "can_be_blank": true, "is_monetary": false },
                { "name": "a__b", "scope": [], "can_be_blank": true, "is_monetary": false }
            ] }"#,
        )
        .unwrap();
        assert!(circulation_rule_kinds(&json).is_err());
    }
}
